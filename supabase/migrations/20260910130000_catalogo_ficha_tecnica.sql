-- 5.2) Listado: agrega `etiquetas text[]` y el filtro `_id_etiqueta`.
DROP FUNCTION IF EXISTS public.ecommerce_listar_productos(integer, text, numeric, numeric, text, integer, integer);

CREATE OR REPLACE FUNCTION public.ecommerce_listar_productos(
  _id_categoria integer DEFAULT NULL,
  _material text DEFAULT NULL,
  _precio_min numeric DEFAULT NULL,
  _precio_max numeric DEFAULT NULL,
  _buscador text DEFAULT NULL,
  _pagina integer DEFAULT 1,
  _tam_pagina integer DEFAULT 24,
  _id_etiqueta bigint DEFAULT NULL
)
RETURNS TABLE (
  id bigint,
  nombre text,
  descripcion text,
  precio_venta numeric,
  id_categoria bigint,
  categoria text,
  es_joyeria boolean,
  imagen_portada text,
  total_disponible numeric,
  destacado boolean,
  precio_oferta numeric,
  marca text,
  etiquetas text[],
  total_count bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  WITH base AS (
    SELECT
      p.id, p.nombre, p.descripcion, p.precio_venta, p.id_categoria,
      c.nombre AS categoria, p.es_joyeria,
      (
        SELECT pi.url FROM producto_imagenes pi
        WHERE pi.id_producto = p.id
        ORDER BY pi.orden ASC LIMIT 1
      ) AS imagen_portada,
      CASE
        WHEN p.es_joyeria THEN (
          SELECT count(*)::numeric FROM piezas_inventario pz
          WHERE pz.id_producto = p.id AND pz.estado = 'disponible'
        )
        WHEN p.maneja_inventarios THEN (
          SELECT COALESCE(sum(s.stock), 0) FROM stock s
          WHERE s.id_producto = p.id
        )
        ELSE NULL
      END AS total_disponible,
      p.destacado,
      CASE
        WHEN p.precio_oferta IS NOT NULL
         AND (p.oferta_desde IS NULL OR now() >= p.oferta_desde)
         AND (p.oferta_hasta IS NULL OR now() <= p.oferta_hasta)
        THEN p.precio_oferta
        ELSE NULL
      END AS precio_oferta,
      (SELECT m.nombre FROM marca m WHERE m.id = p.id_marca) AS marca,
      COALESCE((
        SELECT array_agg(e.nombre ORDER BY e.nombre)
        FROM producto_etiquetas pe
        JOIN etiquetas e ON e.id = pe.id_etiqueta
        WHERE pe.id_producto = p.id
      ), '{}') AS etiquetas
    FROM productos p
    JOIN categorias c ON c.id = p.id_categoria
    WHERE p.id_empresa = public.ecommerce_id_empresa()
      AND p.activo = true
      AND (_id_categoria IS NULL OR p.id_categoria = _id_categoria)
      AND (_precio_min IS NULL OR p.precio_venta >= _precio_min)
      AND (_precio_max IS NULL OR p.precio_venta <= _precio_max)
      AND (_buscador IS NULL OR p.nombre ILIKE '%' || _buscador || '%')
      AND (
        _material IS NULL OR EXISTS (
          SELECT 1 FROM producto_variantes v
          WHERE v.id_producto = p.id AND v.material ILIKE _material
        )
      )
      AND (
        _id_etiqueta IS NULL OR EXISTS (
          SELECT 1 FROM producto_etiquetas pe
          WHERE pe.id_producto = p.id AND pe.id_etiqueta = _id_etiqueta
        )
      )
  )
  SELECT
    b.id, b.nombre, b.descripcion, b.precio_venta, b.id_categoria, b.categoria,
    b.es_joyeria, b.imagen_portada, b.total_disponible, b.destacado, b.precio_oferta,
    b.marca, b.etiquetas,
    count(*) OVER() AS total_count
  FROM base b
  ORDER BY b.nombre ASC
  LIMIT GREATEST(_tam_pagina, 1)
  OFFSET GREATEST(_pagina - 1, 0) * GREATEST(_tam_pagina, 1);
$$;

GRANT EXECUTE ON FUNCTION public.ecommerce_listar_productos(integer, text, numeric, numeric, text, integer, integer, bigint)
  TO anon, authenticated, service_role;


-- 5.3) Detalle: agrega medidas, tallas y etiquetas.
DROP FUNCTION IF EXISTS public.ecommerce_producto_detalle(integer);

CREATE OR REPLACE FUNCTION public.ecommerce_producto_detalle(_id_producto integer)
RETURNS TABLE (
  id bigint,
  nombre text,
  descripcion text,
  id_categoria bigint,
  categoria text,
  es_joyeria boolean,
  precio_venta numeric,
  imagen_portada text,
  total_disponible numeric,
  destacado boolean,
  precio_oferta numeric,
  marca text,
  medidas text,
  tallas text,
  etiquetas text[]
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT
    p.id, p.nombre, p.descripcion, p.id_categoria, c.nombre, p.es_joyeria, p.precio_venta,
    (
      SELECT pi.url FROM producto_imagenes pi
      WHERE pi.id_producto = p.id
      ORDER BY pi.orden ASC LIMIT 1
    ) AS imagen_portada,
    CASE
      WHEN p.es_joyeria THEN (
        SELECT count(*)::numeric FROM piezas_inventario pz
        WHERE pz.id_producto = p.id AND pz.estado = 'disponible'
      )
      WHEN p.maneja_inventarios THEN (
        SELECT COALESCE(sum(s.stock), 0) FROM stock s
        WHERE s.id_producto = p.id
      )
      ELSE NULL
    END AS total_disponible,
    p.destacado,
    CASE
      WHEN p.precio_oferta IS NOT NULL
       AND (p.oferta_desde IS NULL OR now() >= p.oferta_desde)
       AND (p.oferta_hasta IS NULL OR now() <= p.oferta_hasta)
      THEN p.precio_oferta
      ELSE NULL
    END AS precio_oferta,
    (SELECT m.nombre FROM marca m WHERE m.id = p.id_marca) AS marca,
    p.medidas,
    p.tallas,
    COALESCE((
      SELECT array_agg(e.nombre ORDER BY e.nombre)
      FROM producto_etiquetas pe
      JOIN etiquetas e ON e.id = pe.id_etiqueta
      WHERE pe.id_producto = p.id
    ), '{}') AS etiquetas
  FROM productos p
  JOIN categorias c ON c.id = p.id_categoria
  WHERE p.id = _id_producto
    AND p.id_empresa = public.ecommerce_id_empresa()
    AND p.activo = true;
$$;

GRANT EXECUTE ON FUNCTION public.ecommerce_producto_detalle(integer) TO anon, authenticated, service_role;


-- 5.4) Variantes: agrega `tallas_disponibles` (distinct de las piezas libres).
DROP FUNCTION IF EXISTS public.ecommerce_variantes_disponibles(integer);

CREATE OR REPLACE FUNCTION public.ecommerce_variantes_disponibles(_id_producto integer)
RETURNS TABLE (
  id_variante bigint,
  material text,
  pureza text,
  precio_venta_sugerido numeric,
  imagen_portada text,
  piezas_disponibles bigint,
  tallas_disponibles text[]
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT
    v.id AS id_variante,
    v.material,
    v.pureza,
    v.precio_venta_sugerido,
    (
      SELECT vi.url FROM producto_variante_imagenes vi
      WHERE vi.id_variante = v.id
      ORDER BY vi.orden ASC LIMIT 1
    ) AS imagen_portada,
    count(pz.id) FILTER (WHERE pz.estado = 'disponible') AS piezas_disponibles,
    COALESCE((
      SELECT array_agg(DISTINCT pz2.talla ORDER BY pz2.talla)
      FROM piezas_inventario pz2
      WHERE pz2.id_variante = v.id AND pz2.estado = 'disponible' AND pz2.talla IS NOT NULL
    ), '{}') AS tallas_disponibles
  FROM producto_variantes v
  JOIN productos p ON p.id = v.id_producto
  LEFT JOIN piezas_inventario pz ON pz.id_variante = v.id AND pz.estado = 'disponible'
  WHERE v.id_producto = _id_producto
    AND p.id_empresa = public.ecommerce_id_empresa()
    AND p.activo = true
  GROUP BY v.id, v.material, v.pureza, v.precio_venta_sugerido
  ORDER BY v.material, v.pureza;
$$;

GRANT EXECUTE ON FUNCTION public.ecommerce_variantes_disponibles(integer) TO anon, authenticated, service_role;


-- 5.5) Piezas de una variante: agrega `talla`.
DROP FUNCTION IF EXISTS public.ecommerce_piezas_disponibles(bigint);

CREATE OR REPLACE FUNCTION public.ecommerce_piezas_disponibles(_id_variante bigint)
RETURNS TABLE (id_pieza bigint, sku text, peso numeric, precio_venta numeric, talla text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT pz.id, pz.sku, pz.peso, pz.precio_venta, pz.talla
  FROM piezas_inventario pz
  WHERE pz.id_variante = _id_variante
    AND pz.id_empresa = public.ecommerce_id_empresa()
    AND pz.estado = 'disponible'
  ORDER BY pz.precio_venta ASC;
$$;

GRANT EXECUTE ON FUNCTION public.ecommerce_piezas_disponibles(bigint) TO anon, authenticated, service_role;
