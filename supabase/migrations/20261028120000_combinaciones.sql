-- Fase C1: tallas y colores con existencia propia (producto_combinaciones).
--
--   producto_combinaciones (id, id_producto, talla, color, color_hex, sku,
--                           codigo_barras, orden, activo)
--   "Playera básica · M · Negro". talla o color pueden ir vacíos ('') cuando
--   el producto solo tiene uno de los dos. Mismo precio que el producto.
--
-- El stock pasa a llevarse por combinación: stock, movimientos_stock y
-- detalle_venta ganan id_combinacion. NULL = producto sin combinaciones, que
-- sigue exactamente igual que antes.
--
-- validarstock / devolverstockaleliminardv descuentan y devuelven de la fila
-- de la combinación. Un producto con combinaciones vendido sin elegir una
-- falla (el POS y la tienda las piden a partir de C2/C3).
--
-- Pendiente para C3 (hoy no se puede vender una combinación): cancelar venta
-- y cancelar apartado devuelven stock por producto, sin id_combinacion.

CREATE TABLE IF NOT EXISTS public.producto_combinaciones (
  id            bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto   bigint  NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  talla         text    NOT NULL DEFAULT '',
  color         text    NOT NULL DEFAULT '',
  color_hex     text    NULL CHECK (color_hex ~ '^#[0-9a-fA-F]{6}$'),
  sku           text    NULL,
  codigo_barras text    NULL,
  orden         integer NOT NULL DEFAULT 0,
  activo        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT producto_combinaciones_uq UNIQUE (id_producto, talla, color),
  CONSTRAINT producto_combinaciones_algo_chk CHECK (talla <> '' OR color <> '')
);
CREATE UNIQUE INDEX IF NOT EXISTS producto_combinaciones_barras_uq
  ON public.producto_combinaciones (codigo_barras)
  WHERE codigo_barras IS NOT NULL AND codigo_barras <> '';

-- Mismos permisos que atributos: ve el personal, escribe quien tiene el
-- módulo de productos (2).
ALTER TABLE public.producto_combinaciones ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS personal_ver ON public.producto_combinaciones;
DROP POLICY IF EXISTS modulo_insertar ON public.producto_combinaciones;
DROP POLICY IF EXISTS modulo_editar ON public.producto_combinaciones;
DROP POLICY IF EXISTS modulo_borrar ON public.producto_combinaciones;
CREATE POLICY personal_ver ON public.producto_combinaciones FOR SELECT TO authenticated
  USING ((SELECT admin_es_personal()));
CREATE POLICY modulo_insertar ON public.producto_combinaciones FOR INSERT TO authenticated
  WITH CHECK ((SELECT admin_tiene_modulo('{2}'::integer[])));
CREATE POLICY modulo_editar ON public.producto_combinaciones FOR UPDATE TO authenticated
  USING ((SELECT admin_tiene_modulo('{2}'::integer[])))
  WITH CHECK ((SELECT admin_tiene_modulo('{2}'::integer[])));
CREATE POLICY modulo_borrar ON public.producto_combinaciones FOR DELETE TO authenticated
  USING ((SELECT admin_tiene_modulo('{2}'::integer[])));
REVOKE ALL ON public.producto_combinaciones FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.producto_combinaciones TO authenticated;

ALTER TABLE public.stock
  ADD COLUMN IF NOT EXISTS id_combinacion bigint NULL
    REFERENCES public.producto_combinaciones(id) ON DELETE CASCADE;
ALTER TABLE public.movimientos_stock
  ADD COLUMN IF NOT EXISTS id_combinacion bigint NULL
    REFERENCES public.producto_combinaciones(id) ON DELETE SET NULL;
ALTER TABLE public.detalle_venta
  ADD COLUMN IF NOT EXISTS id_combinacion bigint NULL
    REFERENCES public.producto_combinaciones(id) ON DELETE SET NULL;

-- Una sola fila de stock por almacén + producto + combinación (NULL cuenta
-- como valor: un producto sin combinaciones tiene una fila por almacén).
CREATE UNIQUE INDEX IF NOT EXISTS stock_almacen_producto_combinacion_uq
  ON public.stock (id_almacen, id_producto, id_combinacion) NULLS NOT DISTINCT;
CREATE INDEX IF NOT EXISTS stock_id_combinacion_idx
  ON public.stock (id_combinacion) WHERE id_combinacion IS NOT NULL;

-- Mismo cuerpo que en 20261019120000_kardex_ventas + id_combinacion.
CREATE OR REPLACE FUNCTION public.validarstock()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
BEGIN
    IF (SELECT p.maneja_inventarios FROM productos p WHERE p.id = NEW.id_producto) THEN

        IF NEW.id_combinacion IS NULL THEN
            IF EXISTS (SELECT 1 FROM producto_combinaciones c
                        WHERE c.id_producto = NEW.id_producto AND c.activo) THEN
                RAISE EXCEPTION 'Elige talla y color de %', NEW.descripcion;
            END IF;
        ELSIF NOT EXISTS (SELECT 1 FROM producto_combinaciones c
                           WHERE c.id = NEW.id_combinacion
                             AND c.id_producto = NEW.id_producto) THEN
            RAISE EXCEPTION 'La talla/color no corresponde al producto %', NEW.descripcion;
        END IF;

        -- Incremento de cantidad sobre un detalle_venta existente (UPDATE)
        IF TG_OP = 'UPDATE' AND NEW.cantidad > OLD.cantidad THEN
            UPDATE stock
               SET stock = stock - (NEW.cantidad - OLD.cantidad)
             WHERE id_producto = NEW.id_producto
               AND id_almacen = NEW.id_almacen
               AND id_combinacion IS NOT DISTINCT FROM NEW.id_combinacion
               AND stock >= (NEW.cantidad - OLD.cantidad);

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Stock insuficiente para el producto %', NEW.descripcion;
            END IF;

            INSERT INTO movimientos_stock (id_almacen, id_producto, id_combinacion, tipo_movimiento, cantidad, fecha, detalle, origen)
            VALUES (NEW.id_almacen, NEW.id_producto, NEW.id_combinacion, 'salida', NEW.cantidad - OLD.cantidad, now(), 'venta: se aumentó la cantidad', 'ventas');
        END IF;

        -- Decremento de cantidad (se devuelve stock): no requiere chequeo,
        -- sumar siempre es seguro, no hay forma de que "falle por falta de stock".
        IF TG_OP = 'UPDATE' AND NEW.cantidad < OLD.cantidad THEN
            UPDATE stock
               SET stock = stock + (OLD.cantidad - NEW.cantidad)
             WHERE id_producto = NEW.id_producto
               AND id_almacen = NEW.id_almacen
               AND id_combinacion IS NOT DISTINCT FROM NEW.id_combinacion;

            INSERT INTO movimientos_stock (id_almacen, id_producto, id_combinacion, tipo_movimiento, cantidad, fecha, detalle, origen)
            VALUES (NEW.id_almacen, NEW.id_producto, NEW.id_combinacion, 'ingreso', OLD.cantidad - NEW.cantidad, now(), 'venta: se redujo la cantidad', 'ventas');
        END IF;

        -- Nuevo ítem en la venta (INSERT)
        IF TG_OP = 'INSERT' THEN
            UPDATE stock
               SET stock = stock - NEW.cantidad
             WHERE id_producto = NEW.id_producto
               AND id_almacen = NEW.id_almacen
               AND id_combinacion IS NOT DISTINCT FROM NEW.id_combinacion
               AND stock >= NEW.cantidad;

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Stock insuficiente para el producto %', NEW.descripcion;
            END IF;

            INSERT INTO movimientos_stock (id_almacen, id_producto, id_combinacion, tipo_movimiento, cantidad, fecha, detalle, origen)
            VALUES (NEW.id_almacen, NEW.id_producto, NEW.id_combinacion, 'salida', NEW.cantidad, now(), 'venta', 'ventas');
        END IF;

    END IF;
    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.devolverstockaleliminardv()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
BEGIN
    -- Verificar si el producto tiene inventario gestionado
    IF (SELECT p.maneja_inventarios FROM productos p WHERE p.id = OLD.id_producto) THEN
        -- Incrementar el stock correspondiente en el almacén
        UPDATE stock
        SET stock = stock + OLD.cantidad
        WHERE id_producto = OLD.id_producto
          AND id_almacen = OLD.id_almacen
          AND id_combinacion IS NOT DISTINCT FROM OLD.id_combinacion;

        IF FOUND THEN
            INSERT INTO movimientos_stock (id_almacen, id_producto, id_combinacion, tipo_movimiento, cantidad, fecha, detalle, origen)
            VALUES (OLD.id_almacen, OLD.id_producto, OLD.id_combinacion, 'ingreso', OLD.cantidad, now(), 'venta: se quitó el producto', 'ventas');
        END IF;
    END IF;

    -- Continuar con la operación de eliminación
    RETURN OLD;
END;
$function$;

-- Guarda las combinaciones de un producto desde su formulario y crea su fila
-- de stock en el almacén elegido.
--   _combinaciones: [{talla, color, color_hex, sku, codigo_barras,
--                     stock, stock_minimo}, ...]  (el orden se respeta)
-- * Combinación nueva en el almacén: se crea con su existencia inicial (y su
--   entrada en el kardex). Ya existente: solo cambia el mínimo; la existencia
--   se mueve en Inventario, igual que en los productos sin combinaciones.
-- * Combinación que ya no viene: se borra; si tiene historial se desactiva;
--   si todavía tiene existencia, error.
-- * Pasar a combinaciones exige que la existencia sin talla esté en 0.
-- Corre con los permisos de quien llama: deciden las policies.
CREATE OR REPLACE FUNCTION public.guardar_combinaciones_producto(
  _id_producto   bigint,
  _id_almacen    bigint,
  _combinaciones jsonb
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  c       jsonb;
  i       integer := 0;
  v_id    bigint;
  v_talla text;
  v_color text;
  v_ids   bigint[] := '{}';
  v_stock numeric;
  r       record;
BEGIN
  IF jsonb_typeof(_combinaciones) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Combinaciones inválidas';
  END IF;

  IF jsonb_array_length(_combinaciones) > 0 THEN
    IF NOT (SELECT p.maneja_inventarios FROM productos p WHERE p.id = _id_producto) THEN
      RAISE EXCEPTION 'Activa "Controlar stock" para usar tallas y colores';
    END IF;
    SELECT COALESCE(sum(s.stock), 0) INTO v_stock
      FROM stock s
     WHERE s.id_producto = _id_producto AND s.id_combinacion IS NULL;
    IF v_stock <> 0 THEN
      RAISE EXCEPTION 'El producto tiene % en existencia sin talla ni color. Déjala en 0 en Inventario antes de usar tallas y colores.', v_stock;
    END IF;
    DELETE FROM stock WHERE id_producto = _id_producto AND id_combinacion IS NULL;
  END IF;

  FOR c IN SELECT * FROM jsonb_array_elements(_combinaciones) LOOP
    v_talla := btrim(COALESCE(c->>'talla', ''));
    v_color := btrim(COALESCE(c->>'color', ''));
    IF v_talla = '' AND v_color = '' THEN
      CONTINUE;
    END IF;

    INSERT INTO producto_combinaciones
           (id_producto, talla, color, color_hex, sku, codigo_barras, orden, activo)
    VALUES (_id_producto, v_talla, v_color,
            NULLIF(btrim(c->>'color_hex'), ''),
            NULLIF(btrim(c->>'sku'), ''),
            NULLIF(btrim(c->>'codigo_barras'), ''),
            i, true)
    ON CONFLICT (id_producto, talla, color) DO UPDATE
       SET color_hex     = EXCLUDED.color_hex,
           sku           = EXCLUDED.sku,
           codigo_barras = EXCLUDED.codigo_barras,
           orden         = EXCLUDED.orden,
           activo        = true
    RETURNING id INTO v_id;
    v_ids := v_ids || v_id;
    i := i + 1;

    IF _id_almacen IS NOT NULL THEN
      IF EXISTS (SELECT 1 FROM stock
                  WHERE id_almacen = _id_almacen AND id_combinacion = v_id) THEN
        UPDATE stock
           SET stock_minimo = COALESCE((c->>'stock_minimo')::numeric, stock_minimo)
         WHERE id_almacen = _id_almacen AND id_combinacion = v_id;
      ELSE
        v_stock := GREATEST(COALESCE((c->>'stock')::numeric, 0), 0);
        INSERT INTO stock (id_almacen, id_producto, id_combinacion, stock, stock_minimo)
        VALUES (_id_almacen, _id_producto, v_id, v_stock,
                GREATEST(COALESCE((c->>'stock_minimo')::numeric, 0), 0));
        IF v_stock > 0 THEN
          INSERT INTO movimientos_stock (id_almacen, id_producto, id_combinacion, tipo_movimiento, cantidad, detalle, origen)
          VALUES (_id_almacen, _id_producto, v_id, 'ingreso', v_stock, 'Existencia inicial', 'inventario');
        END IF;
      END IF;
    END IF;
  END LOOP;

  -- Las que ya no vienen.
  FOR r IN
    SELECT pc.id, pc.talla, pc.color,
           (SELECT COALESCE(sum(s.stock), 0) FROM stock s WHERE s.id_combinacion = pc.id) AS existencia
      FROM producto_combinaciones pc
     WHERE pc.id_producto = _id_producto
       AND pc.activo
       AND NOT (pc.id = ANY (v_ids))
  LOOP
    IF r.existencia <> 0 THEN
      RAISE EXCEPTION 'No se puede quitar % porque todavía tiene % en existencia. Sácala en Inventario primero.',
        concat_ws(' · ', NULLIF(r.talla, ''), NULLIF(r.color, '')), r.existencia;
    END IF;
    IF EXISTS (SELECT 1 FROM detalle_venta WHERE id_combinacion = r.id)
       OR EXISTS (SELECT 1 FROM movimientos_stock WHERE id_combinacion = r.id) THEN
      UPDATE producto_combinaciones SET activo = false WHERE id = r.id;
      DELETE FROM stock WHERE id_combinacion = r.id;
    ELSE
      DELETE FROM producto_combinaciones WHERE id = r.id;
    END IF;
  END LOOP;
END;
$$;
REVOKE ALL ON FUNCTION public.guardar_combinaciones_producto(bigint, bigint, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.guardar_combinaciones_producto(bigint, bigint, jsonb) TO authenticated;
